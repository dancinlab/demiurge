def _circ(a, b):
    r = abs(a - b)
    return min(r, 1.0 - r)


def best_silver_2d_label(idos, denom=8, a_max=12, b_max=12):
    """Fit IDOS = (a + b*sqrt2)/denom  with a,b small integers (the AB cut-and-project
    module Z[sqrt2]/8). Returns (a, b, pred, res). Tests the RANK-2 {1,sqrt2} module."""
    best = None
    for a in range(-a_max, a_max + 1):
        for b in range(-b_max, b_max + 1):
            pred = (a + b * SQRT2) / denom
            # IDOS in [0,1]; only physically meaningful preds count, but allow wrap test
            if pred < -1e-9 or pred > 1.0 + 1e-9:
                continue
            r = abs(idos - pred)
            if best is None or r < best[3]:
                best = (a, b, float(pred), float(r))
    if best is None:
        return (0, 0, 0.0, abs(idos))
    return best


def best_irrational_label(idos, gen, n_max=20):
    best = None
    for n in range(-n_max, n_max + 1):
        pred = (n * gen) % 1.0
        r = _circ(idos, pred)
        if best is None or r < best[2]:
            best = (n, pred, r)
    return (best[0], float(best[1]), float(best[2]))


def best_rational_label(idos, q_max=20):
    best = None
    for q in range(1, q_max + 1):
        for p in range(0, q + 1):
            pred = p / q
            r = _circ(idos, pred)
            if best is None or r < best[3]:
                best = (p, q, float(pred), float(r))
    return best


def annotate(gaps):
    for g in gaps:
        idos = g["idos_plateau"]
        a, b, pred, r = best_silver_2d_label(idos)
        g["silver_2d_module"] = {"a": int(a), "b": int(b), "denom": 8,
                                 "pred": float(pred), "res": float(r),
                                 "uses_sqrt2": bool(b != 0)}
        n1, p1, r1 = best_irrational_label(idos, GAMMA_SILVER_1D)
        g["silver_1d_rotation"] = {"n": int(n1), "pred": float(p1), "res": float(r1)}
        nf, pf, rf = best_irrational_label(idos, GAMMA_FIB_1D)
        g["fib_1d_rotation"] = {"n": int(nf), "pred": float(pf), "res": float(rf)}
        rt = best_rational_label(idos)
        g["rational_floor"] = {"p": int(rt[0]), "q": int(rt[1]),
                               "pred": float(rt[2]), "res": float(rt[3])}
    return gaps


def module_fit_summary(gaps, span, sig_frac, res_tol):
    sig = [g for g in gaps if g["gap_width"] > sig_frac * span]
    if not sig:
        return {"n_sig": 0, "note": "no significant gaps", "sig_frac": sig_frac}

    def stats(key):
        res = [g[key]["res"] for g in sig]
        return {
            "n_matched": int(sum(1 for r in res if r < res_tol)),
            "median_res": float(np.median(res)),
            "max_res": float(np.max(res)),
        }

    s2 = stats("silver_2d_module")
    s1 = stats("silver_1d_rotation")
    f1 = stats("fib_1d_rotation")
    rt = stats("rational_floor")
    # how many sig gaps NEED sqrt2 (b!=0) for their best 2D-module fit
    needs_sqrt2 = int(sum(1 for g in sig
                          if g["silver_2d_module"]["uses_sqrt2"]
                          and g["silver_2d_module"]["res"] < res_tol))
    return {
        "n_sig": len(sig),
        "res_tol": res_tol,
        "sig_frac": sig_frac,
        "silver_2d_module": s2,
        "silver_1d_rotation": s1,
        "fib_1d_rotation": f1,
        "rational_floor": rt,
        "n_sig_needing_sqrt2": needs_sqrt2,
    }


