# Ammann-Beenker via cut-and-project Z^4 -> R^2(phys) + R^2(internal)
# --------------------------------------------------------------------------- #
def ab_cut_and_project(box=8):
    """Standard octagonal cut-and-project of Z^4 -> R^2(phys) + R^2(internal).
    Physical star  e_k = (cos k*pi/4, sin k*pi/4), k=0..3.
    Internal star  f_k = (cos 3k*pi/4, sin 3k*pi/4), k=0..3 (Galois conjugate, mult=3).
    ACCEPTANCE WINDOW = the projection of the unit 4-cube [-1/2,1/2]^4 into internal
    space (= a regular octagon). Membership: |x* . u_j| <= hw for the 4 octagon normals
    u_j = e_j, with hw = max over the 16 cube vertices of |u_j . (cubevert @ F)| =
    (1 + 1/sqrt2)/sqrt2 ... computed exactly from the cube projection (= 1.2071..).
    Accepted physical images = Ammann-Beenker vertices (tiling edge length exactly 1).
    Returns array of accepted physical-space vertex coordinates.
    """
    from itertools import product
    k = np.arange(4)
    E = np.stack([np.cos(k * np.pi / 4.0), np.sin(k * np.pi / 4.0)], axis=1)   # 4x2 phys
    F = np.stack([np.cos(3 * k * np.pi / 4.0), np.sin(3 * k * np.pi / 4.0)], axis=1)  # 4x2 int
    u = E  # octagon normals (8-fold; 4 axes +/- give 8 facets)

    # window half-width along each normal = the exact unit-cube projection extent
    cubeverts = np.array(list(product([-0.5, 0.5], repeat=4)))
    Wint = cubeverts @ F                       # 16 internal-space window vertices
    hw = float(np.max(np.abs(Wint @ u.T)))     # symmetric octagon -> single half-width

    pts = set()
    rng = range(-box, box + 1)
    for a in rng:
        for b in rng:
            for c in rng:
                for d in rng:
                    n = np.array([a, b, c, d], dtype=float)
                    xs = n @ F                 # internal image (2,)
                    if np.all(np.abs(u @ xs) <= hw + 1e-9):
                        xp = n @ E             # physical image
                        pts.add((round(xp[0], 6), round(xp[1], 6)))
    if not pts:
        return np.zeros((0, 2)), hw
    return np.array(sorted(pts)), hw


def nn_edges(P, edge_len=1.0, tol=1e-3):
    """Edges = vertex pairs at the Ammann-Beenker tiling edge length (= 1, the unit
    star-vector length), NOT the minimum pairwise distance (a boundary diagonal can be
    shorter). Returns adjacency matrix (float, hopping=1) and the edge length used."""
    N = len(P)
    diff = P[:, None, :] - P[None, :, :]
    D = np.sqrt((diff ** 2).sum(-1))
    np.fill_diagonal(D, np.inf)
    A = np.zeros((N, N), dtype=float)
    mask = np.abs(D - edge_len) < tol
    A[mask] = 1.0
    return A, float(edge_len)


def select_bulk(P, A, radius):
    """Take the central DISK of the cut-and-project patch (a connected bulk region) and
    re-derive its induced adjacency. A radial cut (not a coordination cascade) gives a
    clean, large bulk: the AB patch is a big disk and the only finite-size artefacts are
    the dangling edges of the outer ring, which a radius cut < patch radius removes in
    one shot without cascading the whole disk away. AB bulk coordination is 3..8."""
    r = np.sqrt((P ** 2).sum(1))
    keep = r <= radius
    idx = np.where(keep)[0]
    Pb = P[idx]
    Ab = A[np.ix_(idx, idx)]
    # one pass: drop any remaining strict danglers (coord<=1) created by the cut
    for _ in range(3):
        coord = Ab.sum(1)
        k2 = coord >= 2
        if k2.all():
            break
        j = np.where(k2)[0]
        Pb = Pb[j]
        Ab = Ab[np.ix_(j, j)]
    return Pb, Ab


def square_lattice(L):
    """Periodic 2D square lattice (LxL, PBC) vertex tight-binding control."""
    N = L * L
    A = np.zeros((N, N), dtype=float)

    def idx(i, j):
        return (i % L) * L + (j % L)

    for i in range(L):
        for j in range(L):
            a = idx(i, j)
            for di, dj in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                A[a, idx(i + di, j + dj)] = 1.0
    return A


