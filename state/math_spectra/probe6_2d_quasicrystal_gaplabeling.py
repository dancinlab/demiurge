# IDOS gap reader (reuses probe4/5)
# --------------------------------------------------------------------------- #
def spectrum(A):
    return np.sort(np.linalg.eigvalsh(A))


def find_major_gaps(evals, n_gaps=10):
    N = len(evals)
    gaps = np.diff(evals)
    order = np.argsort(gaps)[::-1]
    out = []
    for i in order[:n_gaps]:
        out.append({
            "gap_width": float(gaps[i]),
            "idos_plateau": float((i + 1) / N),
            "E_lo": float(evals[i]),
            "E_hi": float(evals[i + 1]),
        })
    return out


